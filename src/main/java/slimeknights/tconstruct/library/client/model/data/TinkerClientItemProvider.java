/**
 * Generates the client item definitions ({@code assets/<namespace>/items/<id>.json}) for every item in the namespace, required since 1.21.4.
 * The item model type is chosen from the custom loader used by the item model JSON (found through the parent chain in the resource manager), or from the item class
 * when the model is generated by another provider in the same run. Old style {@code overrides} in the item model JSON are converted into
 * {@code minecraft:condition} and {@code minecraft:range_dispatch} trees, later overrides taking priority like vanilla overrides did.
 */
public class TinkerClientItemProvider extends GenericDataProvider {
  /** Maps custom model loaders to the item model type that renders them dynamically */
  private static final Map<String,String> LOADER_TYPES = Map.of(
    "tconstruct:tool", ToolModel.Unbaked.ID.toString(),
    "tconstruct:material", MaterialModel.Unbaked.ID.toString(),
    "tconstruct:fluid_container", FluidContainerModel.Unbaked.ID.toString(),
    "tconstruct:gui", UniqueGuiModel.Unbaked.ID.toString(),
    "tconstruct:tank", TankModel.ITEM_ID.toString(),
    "tconstruct:fluid_texture", FluidTextureModel.ID.toString(),
    "tconstruct:material_block", MaterialBlockModel.ID.toString(),
    "mantle:nbt_key", "mantle:nbt_key",
    "mantle:retextured", "mantle:retextured"
  );
  /** Plain model type */
  private static final String MODEL_TYPE = "minecraft:model";
  /** Property used with {@code minecraft:condition}, all others use {@code minecraft:range_dispatch} */
  private static final Set<String> CONDITION_PROPERTIES = Set.of("tconstruct:broken");
  /** Default color of the tinkers chest, from {@code TinkersChestBlockEntity#DEFAULT_COLOR} */
  private static final int CHEST_DEFAULT_COLOR = 0xFF407686;
  /** Spawn egg colors, the egg colors moved from the item to the client item in 26.3 */
  private static final Map<String,int[]> SPAWN_EGG_COLORS = Map.of(
    "sky_slime_spawn_egg", new int[] {0xFF47EFF5, 0xFFACFFF4},
    "ender_slime_spawn_egg", new int[] {0xFF6300B0, 0xFFD37CFF},
    "terracube_spawn_egg", new int[] {0xFFAFB9D6, 0xFFA1A7B1}
  );

  /** Items only registered when another mod is loaded, such as the minotaur axe with Twilight Forest. Datagen runs without those mods, but the client item is still needed */
  private static final List<Identifier> CONDITIONAL_ITEMS = List.of(TConstruct.getResource("minotaur_axe"));

  private final ResourceManager resourceManager;
  private final String modId;

  public TinkerClientItemProvider(PackOutput output, ResourceManager resourceManager, String modId) {
    super(output, Target.RESOURCE_PACK, "items");
    this.resourceManager = resourceManager;
    this.modId = modId;
  }

  public TinkerClientItemProvider(PackOutput output, ResourceManager resourceManager) {
    this(output, resourceManager, TConstruct.MOD_ID);
  }

  @Override
  public CompletableFuture<?> run(CachedOutput cache) {
    Set<Item> blockTinted = getBlockTintedItems();
    Stream.Builder<CompletableFuture<?>> futures = Stream.builder();
    for (Map.Entry<net.minecraft.resources.ResourceKey<Item>,Item> entry : BuiltInRegistries.ITEM.entrySet()) {
      Identifier id = entry.getKey().identifier();
      if (id.getNamespace().equals(modId)) {
        try {
          futures.add(saveJson(cache, id, definition(id, entry.getValue(), blockTinted)));
        } catch (IOException e) {
          return CompletableFuture.failedFuture(e);
        }
      }
    }
    for (Identifier id : CONDITIONAL_ITEMS) {
      if (id.getNamespace().equals(modId) && !BuiltInRegistries.ITEM.containsKey(id)) {
        try {
          futures.add(saveJson(cache, id, definition(id, null, blockTinted)));
        } catch (IOException e) {
          return CompletableFuture.failedFuture(e);
        }
      }
    }
    return allOf(futures.build());
  }

  @Override
  public String getName() {
    return modId + " Client Item Definition Provider";
  }


  /* Model reading */

  /** Model data found by walking the parent chain */
  private record ModelInfo(boolean exists, @Nullable String loader, @Nullable JsonArray overrides) {
    private static final ModelInfo MISSING = new ModelInfo(false, null, null);
  }

  /** Cache of model info */
  private final Map<Identifier,ModelInfo> modelCache = new HashMap<>();

  /** Reads a model JSON from the resource manager, or returns null if not present (such as models generated in the same run) */
  @Nullable
  private JsonObject readModel(Identifier model) throws IOException {
    Optional<Resource> resource = resourceManager.getResource(model.withPath(path -> "models/" + path + ".json"));
    if (resource.isEmpty()) {
      return null;
    }
    try (Reader reader = resource.get().openAsReader()) {
      return GsonHelper.parse(reader);
    }
  }

  /** Gets the loader name from the model JSON */
  @Nullable
  private static String getLoader(JsonObject json) {
    if (json.has("loader")) {
      JsonElement loader = json.get("loader");
      if (loader.isJsonObject()) {
        return GsonHelper.getAsString(loader.getAsJsonObject(), "id");
      }
      return loader.getAsString();
    }
    return null;
  }

  /** Normalizes a model location, adding the minecraft namespace if missing */
  private static Identifier modelId(String name) {
    return Identifier.parse(name);
  }

  /** Gets the model info for the given model, walking parents until a loader is found */
  private ModelInfo getModelInfo(Identifier model) throws IOException {
    ModelInfo cached = modelCache.get(model);
    if (cached != null) {
      return cached;
    }
    ModelInfo info = ModelInfo.MISSING;
    JsonArray overrides = null;
    boolean exists = false;
    String loader = null;
    Set<Identifier> visited = new HashSet<>();
    Identifier current = model;
    while (current != null && visited.add(current)) {
      JsonObject json = readModel(current);
      if (json == null) {
        break;
      }
      if (current == model) {
        exists = true;
      }
      if (overrides == null && json.has("overrides")) {
        overrides = GsonHelper.getAsJsonArray(json, "overrides");
      }
      loader = getLoader(json);
      if (loader != null) {
        // neoforge composite and similar loaders are static, keep looking only for our known loaders
        if (LOADER_TYPES.containsKey(loader)) {
          break;
        }
        loader = null;
      }
      current = json.has("parent") ? modelId(GsonHelper.getAsString(json, "parent")) : null;
    }
    if (exists) {
      info = new ModelInfo(true, loader, overrides);
    }
    modelCache.put(model, info);
    return info;
  }


  /* Definitions */

  /** Creates a simple item model object */
  private static JsonObject itemModel(String type, Identifier model) {
    JsonObject json = new JsonObject();
    json.addProperty("type", type);
    json.addProperty("model", model.toString());
    return json;
  }

  /** Gets the item model type for an item whose model could not be read */
  private static String getFallbackType(Item item) {
    if (item instanceof IMaterialItem) {
      return MaterialModel.Unbaked.ID.toString();
    }
    if (item instanceof BucketItem) {
      return FluidContainerModel.Unbaked.ID.toString();
    }
    if (item instanceof TankItem) {
      return TankModel.ITEM_ID.toString();
    }
    if (item instanceof BlockItem blockItem && blockItem.getBlock() instanceof RetexturedBlock) {
      return "mantle:retextured";
    }
    return MODEL_TYPE;
  }

  /** Gets the item model type for the given model */
  private String getType(Identifier model, @Nullable Item item) throws IOException {
    ModelInfo info = getModelInfo(model);
    if (info.exists) {
      return info.loader == null ? MODEL_TYPE : LOADER_TYPES.get(info.loader);
    }
    return item != null ? getFallbackType(item) : null;
  }

  /** Creates the definition for the given item, item is null for {@link #CONDITIONAL_ITEMS} that are not registered */
  private JsonObject definition(Identifier id, @Nullable Item item, Set<Item> blockTinted) throws IOException {
    Identifier model = id.withPrefix("item/");
    ModelInfo info = getModelInfo(model);
    String type = getType(model, item);
    JsonObject itemModel = itemModel(type, model);

    // tints, only apply to plain models
    if (MODEL_TYPE.equals(type)) {
      JsonArray tints = getTints(id, item, blockTinted);
      if (tints != null) {
        itemModel.add("tints", tints);
      }
    }

    // convert overrides
    if (info.overrides != null) {
      JsonObject fallback = itemModel;
      for (JsonElement element : info.overrides) {
        JsonObject override = GsonHelper.convertToJsonObject(element, "override");
        Identifier overrideModel = modelId(GsonHelper.getAsString(override, "model"));
        // overrides of generated models cannot be read, they use the same type as the base model (tool variants for tools)
        String overrideType = getType(overrideModel, null);
        if (overrideType == null) {
          overrideType = type;
        }
        JsonObject selected = itemModel(overrideType, overrideModel);
        fallback = predicateModel(GsonHelper.getAsJsonObject(override, "predicate"), selected, fallback);
      }
      itemModel = fallback;
    }

    JsonObject definition = new JsonObject();
    definition.add("model", itemModel);
    return definition;
  }

  /** Wraps the selected model in conditions for every property in the predicate, the fallback is used when any predicate fails */
  private static JsonObject predicateModel(JsonObject predicate, JsonObject selected, JsonObject fallback) {
    JsonObject model = selected;
    for (Map.Entry<String,JsonElement> entry : predicate.entrySet()) {
      String property = entry.getKey();
      if (CONDITION_PROPERTIES.contains(property)) {
        JsonObject condition = new JsonObject();
        condition.addProperty("type", "minecraft:condition");
        condition.addProperty("property", property);
        condition.add("on_true", model);
        condition.add("on_false", fallback.deepCopy());
        model = condition;
      } else {
        JsonObject range = new JsonObject();
        range.addProperty("type", "minecraft:range_dispatch");
        range.addProperty("property", property);
        JsonArray entries = new JsonArray();
        JsonObject rangeEntry = new JsonObject();
        rangeEntry.addProperty("threshold", entry.getValue().getAsFloat());
        rangeEntry.add("model", model);
        entries.add(rangeEntry);
        range.add("entries", entries);
        range.add("fallback", fallback.deepCopy());
        model = range;
      }
    }
    return model;
  }


  /* Tints */

  /** Adds all items from the given objects */
  private static void addItems(Set<Item> items, List<? extends ItemLike> objects) {
    for (ItemLike object : objects) {
      items.add(object.asItem());
    }
  }

  /** Gets the set of items using block colors */
  private static Set<Item> getBlockTintedItems() {
    Set<Item> items = new HashSet<>();
    for (EnumObject<?,?> grass : List.of(TinkerWorld.vanillaSlimeGrass, TinkerWorld.earthSlimeGrass, TinkerWorld.skySlimeGrass, TinkerWorld.enderSlimeGrass, TinkerWorld.ichorSlimeGrass)) {
      addItems(items, grass.values().stream().map(block -> (ItemLike) block).toList());
    }
    addItems(items, TinkerWorld.slimeLeaves.values());
    addItems(items, TinkerWorld.slimeFern.values());
    addItems(items, TinkerWorld.slimeTallGrass.values());
    items.add(TinkerWorld.skySlimeVine.asItem());
    items.add(TinkerWorld.enderSlimeVine.asItem());
    return items;
  }

  /** Creates a tint object of the given type */
  private static JsonObject tint(String type) {
    JsonObject tint = new JsonObject();
    tint.addProperty("type", type);
    return tint;
  }

  /** Creates a constant tint */
  private static JsonObject constant(int color) {
    JsonObject tint = tint("minecraft:constant");
    tint.addProperty("value", color);
    return tint;
  }

  /** Gets the tints for the given item, replacing the item colors from 1.21.1 */
  @Nullable
  private static JsonArray getTints(Identifier id, Item item, Set<Item> blockTinted) {
    JsonArray tints = new JsonArray();
    if (item instanceof PotionBucketItem) {
      // potion contents color on layer 0, layer 1 untinted. Default matches PotionContents#getColor for potions without effects
      JsonObject potion = tint("minecraft:potion");
      potion.addProperty("default", -13083194);
      tints.add(potion);
    } else if (item == TinkerTables.tinkersChest.asItem()) {
      JsonObject dye = tint("minecraft:dye");
      dye.addProperty("default", CHEST_DEFAULT_COLOR);
      tints.add(dye);
    } else if (item == TinkerModifiers.modifierCrystal.asItem()) {
      tints.add(tint(ModifierCrystalTint.ID.toString()));
    } else if (blockTinted.contains(item)) {
      tints.add(tint(BlockItemTintSource.ID.toString()));
    } else {
      int[] eggColors = SPAWN_EGG_COLORS.get(id.getPath());
      if (eggColors == null) {
        return null;
      }
      for (int color : eggColors) {
        tints.add(constant(color));
      }
    }
    return tints;
  }
}
