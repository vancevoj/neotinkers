package slimeknights.tconstruct.common.data.model;

import net.minecraft.client.renderer.texture.atlas.sources.DirectoryLister;
import net.minecraft.client.renderer.texture.atlas.sources.PalettedPermutations;
import net.minecraft.client.renderer.texture.atlas.sources.SingleFile;
import net.minecraft.core.HolderLookup;
import net.minecraft.data.AtlasIds;
import net.minecraft.data.PackOutput;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.equipment.trim.TrimMaterials;
import net.neoforged.neoforge.client.data.SpriteSourceProvider;
import slimeknights.tconstruct.TConstruct;
import slimeknights.tconstruct.library.client.modifiers.model.TrimModifierModel;
import slimeknights.tconstruct.library.client.modifiers.model.TrimModifierModel.Armor;
import slimeknights.tconstruct.tools.client.ShieldBannerModifierSpriteSource;
import slimeknights.tconstruct.tools.data.material.MaterialIds;

import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Provider to stitch textures from additional folders
 */
public class TinkerSpriteSourceProvider extends SpriteSourceProvider {
  /** List of trim variants supported, must all exist in vanilla */
  /** Palette folder for trim materials, since 26.3 relative to {@code textures/palettes} */
  private static final String PALETTE_FOLDER = "trim/";

  public TinkerSpriteSourceProvider(PackOutput output, CompletableFuture<HolderLookup.Provider> lookupProvider) {
    super(output, lookupProvider, TConstruct.MOD_ID);
  }

  @Override
  protected void gather() {
    // since 26.3 the base trim palette is minecraft:trim_base at textures/palettes/trim_base.png
    Identifier trimPalette = Identifier.withDefaultNamespace("trim_base");
    // map of material suffix to material palette for trims, palettes generated by TinkerTrimMaterialPaletteGenerator at textures/palettes/trim/
    Map<String,Identifier> tinkerMaterials = Arrays.stream(MaterialIds.TRIM_MATERIALS).collect(Collectors.toMap(id -> id.getNamespace() + "_" + id.getPath(), id -> id.withPrefix(PALETTE_FOLDER)));
    Map<String,Identifier> vanillaMaterials = new HashMap<>();
    addVanilla(vanillaMaterials, TrimMaterials.Palette.QUARTZ);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.IRON);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.NETHERITE);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.REDSTONE);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.COPPER);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.GOLD);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.EMERALD);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.DIAMOND);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.LAPIS);
    addVanilla(vanillaMaterials, TrimMaterials.Palette.AMETHYST);
    // custom armor "modifier" textures that use the trim materials
    List<Identifier> customItemTrims = Stream.of("item/tool/armor/travelers/goggles/trim", "item/tool/armor/slime/wings/trim").map(TConstruct::getResource).toList();

    atlas(AtlasIds.BLOCKS)
      // we typically use this directory for modifier icons that are not items nor blocks
      .addSource(directory("gui/modifiers"))
      // patterns load from this directory
      .addSource(directory("gui/tinker_pattern"));
    // since 1.21.11 item textures are on the item atlas
    SourceList items = atlas(AtlasIds.ITEMS)
      // trim armor icons
      .addSource(new PalettedPermutations(
        Stream.concat(Arrays.stream(Armor.values()).map(Armor::getRoot), customItemTrims.stream()).toList(),
        trimPalette, tinkerMaterials))
      // trim shield icons
      .addSource(new PalettedPermutations(customItemTrims, trimPalette, vanillaMaterials))
      // banner modifier icons
      .addSource(new ShieldBannerModifierSpriteSource(2, 2, 10, 20, TConstruct.getResource("item/tool/armor/plate/shield/banner_large/"), 11, 8, 32));
    // add untinted trim textures, we use them as fallbacks
    for (Armor armor : TrimModifierModel.Armor.values()) {
      items.addSource(new SingleFile(armor.getRoot(), Optional.empty()));
    }
    // since 26.3 armor trims on entities are generated from the trim material palette when rendering, so the armor trims atlas is gone
  }

  /** Creates a directory lister where the source matches the prefix. */
  private static DirectoryLister directory(String path) {
    return new DirectoryLister(path, path + '/');
  }

  /** Adds a vanilla material palette to the map */
  private static void addVanilla(Map<String,Identifier> map, TrimMaterials.Palette palette) {
    map.put(palette.suffix(), palette.id());
  }
}
